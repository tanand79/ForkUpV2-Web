import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.join(root, "..");
const target = path.join(webRoot, ".env.production");
const source = path.join(webRoot, "_env.production");
const sourceExample = path.join(webRoot, "_env.production.example");

function isLoopbackApiUrl(url) {
  try {
    const host = new URL(url).hostname.toLowerCase();
    return host === "localhost" || host === "127.0.0.1" || host === "[::1]";
  } catch {
    return false;
  }
}

function readApiUrlFromEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return "";
  const match = fs
    .readFileSync(filePath, "utf8")
    .match(/^\s*NEXT_PUBLIC_API_URL\s*=\s*(.+)\s*$/m);
  return match?.[1]?.trim().replace(/^["']|["']$/g, "") ?? "";
}

// Amplify / CI: prefer already-set process env. Otherwise sync from _env.production.
const fromProcess = (process.env.NEXT_PUBLIC_API_URL ?? "").trim();
if (fromProcess) {
  fs.writeFileSync(
    target,
    `# Generated by ensure-production-env.mjs from process env\nNEXT_PUBLIC_API_URL=${fromProcess}\n`,
    "utf8",
  );
  console.log("Wrote web/.env.production from process.env.NEXT_PUBLIC_API_URL");
} else if (fs.existsSync(source)) {
  fs.copyFileSync(source, target);
  console.log("Wrote web/.env.production from _env.production");
} else if (fs.existsSync(sourceExample)) {
  fs.copyFileSync(sourceExample, target);
  console.log("Wrote web/.env.production from _env.production.example");
} else {
  console.error(
    "Missing NEXT_PUBLIC_API_URL: supply Amplify env or Forkup-Web/_env.production",
  );
  process.exit(1);
}

const resolved =
  fromProcess ||
  readApiUrlFromEnvFile(target) ||
  readApiUrlFromEnvFile(source) ||
  readApiUrlFromEnvFile(sourceExample);

if (!resolved) {
  console.error("NEXT_PUBLIC_API_URL is empty for production build");
  process.exit(1);
}

if (isLoopbackApiUrl(resolved)) {
  console.error(
    `Refusing production build with loopback API URL: ${resolved}\n` +
      "Set Amplify Environment variable NEXT_PUBLIC_API_URL to your EC2 API, e.g. http://54.242.154.3:3001",
  );
  process.exit(1);
}

console.log(`Production API URL: ${resolved}`);
